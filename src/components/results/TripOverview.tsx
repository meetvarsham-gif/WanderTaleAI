import { Info } from 'lucide-react';
import type { TripResult } from '../../types';
import { INTEREST_OPTIONS } from '../../types';
import './TripOverview.css';

export default function TripOverview({ trip }: { trip: TripResult }) {
  const interestLabels = (trip.input.interests.length
    ? trip.input.interests
    : (['culture', 'food', 'nature'] as const)
  ).map((tag) => INTEREST_OPTIONS.find((o) => o.tag === tag)?.label ?? tag);

  return (
    <section className="result-section result-section-tight overview">
      <div className="container overview-grid">
        <div className="overview-stats">
          <div className="overview-stat">
            <span className="overview-stat-value">{trip.itinerary.length}</span>
            <span className="overview-stat-label">Days Planned</span>
          </div>
          <div className="overview-stat">
            <span className="overview-stat-value">{trip.itinerary.reduce((n, d) => n + d.activities.length, 0)}</span>
            <span className="overview-stat-label">Suggested Activities</span>
          </div>
          <div className="overview-stat">
            <span className="overview-stat-value">{interestLabels.length}</span>
            <span className="overview-stat-label">Interests Woven In</span>
          </div>
        </div>

        <div className="overview-details">
          <div className="overview-detail-block">
            <h4>Shaped around</h4>
            <div className="overview-chip-row">
              {interestLabels.map((l) => (
                <span key={l} className="pill">
                  {l}
                </span>
              ))}
            </div>
          </div>

          {trip.input.preferences && (
            <div className="overview-detail-block">
              <h4>Noted preferences</h4>
              <p className="overview-preferences">"{trip.input.preferences}"</p>
            </div>
          )}

          <div className="overview-mode-note">
            <Info size={15} strokeWidth={1.7} />
            <span>
              Generated by WanderTale's <strong>local demo engine</strong> — rule-based and template-driven, not a
              connected AI model. Structured to be swapped for a real LLM later without changing this interface.
            </span>
          </div>
        </div>
      </div>
    </section>
  );
}
