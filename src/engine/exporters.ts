import type { ConsistencyReport, TripResult } from '../types';

export function buildExportJson(trip: TripResult, report: ConsistencyReport | null): string {
  return JSON.stringify({ trip, consistencyReport: report }, null, 2);
}

export function buildExportText(trip: TripResult, report: ConsistencyReport | null): string {
  const lines: string[] = [];
  const { input } = trip;

  lines.push('WANDERTALE AI — TRAVEL STORY');
  lines.push('='.repeat(40));
  lines.push(`Destination: ${input.destination}`);
  lines.push(`Duration: ${input.durationDays} day(s)`);
  if (input.startDate) lines.push(`Starting: ${input.startDate}`);
  lines.push(`Travellers: ${input.travelers}`);
  if (input.budget) lines.push(`Budget: ${input.budget} ${input.currency}`);
  lines.push(`Travel style: ${input.travelStyle}`);
  if (input.interests.length) lines.push(`Interests: ${input.interests.join(', ')}`);
  lines.push('');
  lines.push(trip.destinationSummary);
  lines.push('');
  lines.push(`Generated by: ${trip.mode === 'local-demo' ? 'Local demo mode (rule-based, no paid AI API)' : trip.mode}`);
  lines.push('');

  trip.itinerary.forEach((day) => {
    const story = trip.story.find((s) => s.day === day.day);
    const scene = trip.scenes.find((s) => s.day === day.day);

    lines.push('-'.repeat(40));
    lines.push(`DAY ${day.day}${day.date ? ` — ${day.date}` : ''}: ${day.theme}`);
    lines.push('-'.repeat(40));
    lines.push('');
    lines.push('Itinerary (suggestions — verify locally):');
    day.activities.forEach((a) => {
      lines.push(`  [${a.time}] ${a.title} — ${a.location}`);
      lines.push(`    ${a.description}`);
    });
    lines.push(`  Note: ${day.travelNote}`);
    lines.push('');

    if (story) {
      lines.push('Story:');
      lines.push(`  ${story.text}`);
      lines.push('');
    }

    if (scene) {
      lines.push('Visual scene:');
      lines.push(`  ${scene.sceneDescription}`);
      lines.push(`  Image prompt: ${scene.imagePrompt}`);
      lines.push(`  Caption: ${scene.caption}`);
      lines.push('');
    }
  });

  if (report) {
    lines.push('='.repeat(40));
    lines.push('CONSISTENCY REPORT (local-demo rule-based checker)');
    lines.push('='.repeat(40));
    lines.push(`Overall result: ${report.passed ? 'PASSED' : 'ISSUES FOUND'}`);
    lines.push('');
    lines.push('Checks performed:');
    report.checksPerformed.forEach((c) => {
      lines.push(`  [${c.status.toUpperCase()}] ${c.label} — ${c.details}`);
    });
    if (report.issues.length) {
      lines.push('');
      lines.push('Issues found:');
      report.issues.forEach((i) => {
        lines.push(`  (${i.severity.toUpperCase()}) ${i.description}`);
        lines.push(`    Suggested correction: ${i.suggestedCorrection}`);
      });
    }
  }

  return lines.join('\n');
}

export function downloadTextFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
